#include <iostream>
#include <algorithm>
#include <vector>
using namespace std;

int findMin(int inArray[], const int size) {
    int minimum = inArray[0];
    for (int i = 1; i < size; ++i) {
        if (inArray[i] < minimum) minimum = inArray[i];
    }
    return minimum;
}

int findMax(int inArray[], const int size) {
    int maximum = inArray[0];
    for (int i = 1; i < size; ++i) {
        if (inArray[i] > maximum) maximum = inArray[i];
    }
    return maximum;
}

// A double return type preserves fractional averages.
double computeAverage(int inArray[], const int size) {
    long long total = 0;
    for (int i = 0; i < size; ++i) total += inArray[i];
    return static_cast<double>(total) / size;
}

// A double return type is needed because an even-sized set can have
// a median ending in .5.
double computeMedian(int inArray[], const int size) {
    vector<int> sortedMarks(inArray, inArray + size);
    sort(sortedMarks.begin(), sortedMarks.end());

    if (size % 2 == 1) {
        return sortedMarks[size / 2];
    }

    return (sortedMarks[size / 2 - 1] + sortedMarks[size / 2]) / 2.0;
}

int main() {
    int numberOfStudents;

    cout << "Enter the number of students: ";
    cin >> numberOfStudents;

    if (numberOfStudents <= 0) {
        cout << "The number of students must be greater than zero.\n";
        return 1;
    }

    int* marks = new int[numberOfStudents];

    for (int i = 0; i < numberOfStudents; ++i) {
        do {
            cout << "Enter mark for student " << i + 1 << " (0 or above): ";
            cin >> marks[i];

            if (marks[i] < 0) {
                cout << "Invalid mark. Negative marks are not accepted.\n";
            }
        } while (marks[i] < 0);
    }

    cout << "\n--- Class Statistics ---\n";
    cout << "Minimum mark: " << findMin(marks, numberOfStudents) << '\n';
    cout << "Maximum mark: " << findMax(marks, numberOfStudents) << '\n';
    cout << "Average mark: " << computeAverage(marks, numberOfStudents) << '\n';
    cout << "Median mark: " << computeMedian(marks, numberOfStudents) << '\n';

    delete[] marks;
    return 0;
}